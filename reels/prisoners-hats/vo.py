"""Voice-over for the 100 Prisoners and the Hat Line reel (Kokoro TTS via kokoro-onnx).

usage: python vo.py MODEL.onnx VOICES.bin [voice]
Writes vo/NN.wav (44.1 kHz mono) and vo.js. Each line is one scene of the animation;
`cap` is the on-screen caption pill and `extra` is how long the scene holds after the line.
"""
import json
import os
import subprocess
import sys

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

LINES = [  # (narration, caption, extra hold in seconds)
    ("The warden offers one hundred prisoners a deal.", "A deal for 100 prisoners", 0.5),
    ("Tomorrow, they'll stand in one long line, all facing forward, and each one gets a red or a blue hat.", "Red or blue hats", 0.6),
    ("Nobody can see their own hat. Only the hats of everyone in front of them.", "You only see the hats ahead", 0.5),
    ("Starting at the back, each prisoner says one word: red, or blue.", "Back to front: one word each", 0.6),
    ("Name your own hat color, and you walk free. Get it wrong, and you stay locked up.", "Right = free. Wrong = stay", 0.6),
    ("Everyone hears every answer, but no one can say anything else.", "No other talking", 0.4),
    ("Tonight, they can make a plan. How many can they save for sure?", "How many can they save?", 0.5),
    ("What's your plan? Pause, and comment it below!", "Comment your plan!", 9.2),
    ("Here's the trick. The prisoner at the back counts the red hats in front of them.", "Back prisoner counts red hats", 0.6),
    ("If the number is even, they say blue. If it's odd, they say red.", "Even → BLUE · Odd → RED", 0.8),
    ("For them, it's a coin flip. But now everyone else knows the code.", "Now everyone knows the code", 0.5),
    ("Let's try it with five prisoners.", "Try it with 5", 0.6),
    ("The back prisoner sees two red hats. Two is even, so they say: blue.", "2 reds = even → BLUE", 0.7),
    ("Their own hat is red, so they lose the coin flip. That's the price of the code.", "The back one gambles", 0.5),
    ("Next in line sees only one red hat. That's odd, but the code said even. So the missing red is on their own head. Red!", "1 is odd ≠ even → RED", 0.6),
    ("From here, each prisoner adds the reds they've heard behind them to the reds they can see ahead.", "Reds heard + reds seen", 0.5),
    ("If even or odd matches the code, their hat is blue. If it doesn't, it's red.", "Match → BLUE · No match → RED", 0.6),
    ("Blue. Red. Blue. Every one of them is right.", "All correct!", 0.9),
    ("With a hundred prisoners, it works exactly the same.", "Same for 100", 1.4),
    ("Ninety nine walk free, guaranteed. And the one at the back still has a fifty-fifty chance.", "99 free, guaranteed", 1.4),
    ("Would you volunteer to stand at the back? Follow for more puzzles!", "Follow for more puzzles", 1.6),
]

model, voices = sys.argv[1], sys.argv[2]
voice = sys.argv[3] if len(sys.argv) > 3 else 'af_heart'
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(here, 'vo'), exist_ok=True)
kokoro = Kokoro(model, voices)
out = []
for i, (text, cap, extra) in enumerate(LINES):
    samples, sr = kokoro.create(text, voice=voice, speed=1.08, lang='en-us')
    y = np.asarray(samples, dtype=np.float32)
    idx = np.where(np.abs(y) > 0.01)[0]
    y = y[max(0, idx[0] - int(sr * .02)): idx[-1] + int(sr * .06)]
    y = y / (np.max(np.abs(y)) + 1e-9) * 0.9
    raw, dst = os.path.join(here, 'vo', f'{i:02d}_raw.wav'), os.path.join(here, 'vo', f'{i:02d}.wav')
    sf.write(raw, y, sr)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', raw, '-ar', '44100', '-ac', '1', dst], check=True)
    os.remove(raw)
    dur = len(y) / sr
    out.append({'text': text, 'cap': cap, 'dur': round(dur, 3), 'extra': extra, 'file': f'vo/{i:02d}.wav'})
    print(f'{i:02d} {dur:5.2f}s  {text}')

with open(os.path.join(here, 'vo.js'), 'w') as f:
    f.write('// generated by vo.py\nwindow.VO = ' + json.dumps(out) + ';\n')
print('total speech', round(sum(l['dur'] for l in out), 2), 's; with holds', round(sum(l['dur'] + l['extra'] + .25 for l in out), 1), 's')
