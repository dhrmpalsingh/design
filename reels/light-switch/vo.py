"""Generates the voice-over with Kokoro TTS (kokoro-onnx).

usage: python vo.py MODEL.onnx VOICES.bin [voice]
Writes vo/NN.wav (44.1 kHz mono) and vo.js (line anchors + durations read by reel.html).
Each line's `t` is the story time (in reel.html's timeline) where it starts; the page
stretches a scene slightly whenever its lines need more room than the animation gives.
"""
import json
import os
import subprocess
import sys

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

LINES = [
    (0.3, "Can you solve this one? There are three light switches in a hallway."),
    (5.2, "Behind the door, there's a room with one light bulb."),
    (7.65, "No windows. No way to peek."),
    (10.2, "Only one of the switches works that bulb."),
    (14.7, "You can flip them as much as you like..."),
    (16.85, "but you can open the door only once."),
    (19.15, "So, which switch is it?"),
    (22.6, "Pause the video, and comment your answer!"),
    (33.1, "Here's the trick."),
    (35.6, "Turn switch A on..."),
    (37.85, "and wait five minutes."),
    (41.1, "Then, turn A off, and turn B on."),
    (45.1, "Now, open the door."),
    (48.6, "The bulb is off."),
    (51.55, "But touch it... it's warm!"),
    (55.0, "If it's on, it's B."),
    (56.4, "Off, but warm? That's A."),
    (58.6, "Off and cold? That's C."),
    (60.6, "So the answer is switch A!"),
    (63.7, "Did you get it right?"),
    (65.8, "Follow for more riddles!"),
]

model, voices = sys.argv[1], sys.argv[2]
voice = sys.argv[3] if len(sys.argv) > 3 else 'af_heart'
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(here, 'vo'), exist_ok=True)
kokoro = Kokoro(model, voices)
out = []
for i, (t, text) in enumerate(LINES):
    samples, sr = kokoro.create(text, voice=voice, speed=1.05, lang='en-us')
    y = np.asarray(samples, dtype=np.float32)
    # trim silence at both ends, keep a few ms of air
    idx = np.where(np.abs(y) > 0.01)[0]
    y = y[max(0, idx[0] - int(sr * .02)): idx[-1] + int(sr * .06)]
    y = y / (np.max(np.abs(y)) + 1e-9) * 0.9
    raw = os.path.join(here, 'vo', f'{i:02d}_raw.wav')
    dst = os.path.join(here, 'vo', f'{i:02d}.wav')
    sf.write(raw, y, sr)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', raw, '-ar', '44100', '-ac', '1', dst], check=True)
    os.remove(raw)
    dur = len(y) / sr
    out.append({'t': t, 'text': text, 'dur': round(dur, 3), 'file': f'vo/{i:02d}.wav'})
    print(f'{i:02d} {t:6.2f}s +{dur:4.2f}s  {text}')

with open(os.path.join(here, 'vo.js'), 'w') as f:
    f.write('// generated by vo.py\nwindow.VO = ' + json.dumps(out, indent=1) + ';\n')
