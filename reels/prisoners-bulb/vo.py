"""Voice-over for the 100 Prisoners and a Light Bulb reel (Kokoro TTS via kokoro-onnx).

usage: python vo.py MODEL.onnx VOICES.bin [voice]
Writes vo/NN.wav (44.1 kHz mono) and vo.js. Each line is one scene of the animation;
`cap` is the on-screen caption pill and `extra` is how long the scene holds after the line.
"""
import json
import os
import subprocess
import sys

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

LINES = [  # (narration, caption, extra hold in seconds)
    ("One hundred prisoners. One light bulb. Can they all walk free?", "100 prisoners · 1 light bulb", 0.5),
    ("Each prisoner is locked in a cell alone, and they can never talk to each other.", "No talking. Ever.", 0.4),
    ("Every day, the warden picks one prisoner at random, and takes them to a room with a single light bulb.", "1 random prisoner a day", 0.6),
    ("The bulb starts off. Inside, they can flip the switch, or leave it alone.", "Flip it, or leave it", 0.6),
    ("On any day, any prisoner can announce: all one hundred of us have been in that room.", "Anyone can announce", 0.5),
    ("If they're right, everyone goes free. If they're wrong, everyone stays locked up forever.", "Right = free. Wrong = forever.", 0.6),
    ("Before day one, they get one meeting to make a plan.", "1 meeting to plan", 0.5),
    ("What's your plan? Pause, and comment it below!", "Comment your plan!", 9.2),
    ("Here's a plan that works. They pick one prisoner to be the counter.", "Pick 1 counter", 0.6),
    ("Everyone else: the first time you find the bulb off, switch it on. Just once, ever.", "Everyone else: switch it ON once", 0.6),
    ("Only the counter switches it off. And each time, they add one mark to the wall.", "Counter: switch it OFF, +1 mark", 0.6),
    ("So a light that's on means: someone new has been here.", "ON = someone new was here", 0.4),
    ("Say on day two, prisoner twenty three finds it off, and switches it on.", "Day 2: #23 switches it on", 0.5),
    ("Day three, prisoner fifty eight finds it on. Not their signal, so they leave it.", "Day 3: #58 leaves it", 0.5),
    ("Day four, the counter finds it on, switches it off, and makes mark number one.", "Day 4: mark #1", 0.6),
    ("And if twenty three ever finds it off again? They leave it. They've already been counted.", "#23 never switches again", 0.5),
    ("Day after day, the marks pile up.", "Day after day...", 3.2),
    ("When the counter reaches ninety nine marks, plus themselves, that's all one hundred.", "99 marks + the counter = 100", 0.6),
    ("They tell the warden... and everyone walks free!", "Everyone walks free!", 1.6),
    ("The catch? On average, this takes about ten thousand days. That's twenty eight years!", "~10,400 days ≈ 28 years", 0.8),
    ("Could you wait that long? Follow for more puzzles!", "Follow for more puzzles", 1.6),
]

model, voices = sys.argv[1], sys.argv[2]
voice = sys.argv[3] if len(sys.argv) > 3 else 'af_heart'
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(here, 'vo'), exist_ok=True)
kokoro = Kokoro(model, voices)
out = []
for i, (text, cap, extra) in enumerate(LINES):
    samples, sr = kokoro.create(text, voice=voice, speed=1.08, lang='en-us')
    y = np.asarray(samples, dtype=np.float32)
    idx = np.where(np.abs(y) > 0.01)[0]
    y = y[max(0, idx[0] - int(sr * .02)): idx[-1] + int(sr * .06)]
    y = y / (np.max(np.abs(y)) + 1e-9) * 0.9
    raw, dst = os.path.join(here, 'vo', f'{i:02d}_raw.wav'), os.path.join(here, 'vo', f'{i:02d}.wav')
    sf.write(raw, y, sr)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', raw, '-ar', '44100', '-ac', '1', dst], check=True)
    os.remove(raw)
    dur = len(y) / sr
    out.append({'text': text, 'cap': cap, 'dur': round(dur, 3), 'extra': extra, 'file': f'vo/{i:02d}.wav'})
    print(f'{i:02d} {dur:5.2f}s  {text}')

with open(os.path.join(here, 'vo.js'), 'w') as f:
    f.write('// generated by vo.py\nwindow.VO = ' + json.dumps(out) + ';\n')
print('total speech', round(sum(l['dur'] for l in out), 2), 's; with holds', round(sum(l['dur'] + l['extra'] + .25 for l in out), 1), 's')
